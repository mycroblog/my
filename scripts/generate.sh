#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-only
#
# Generate the client API code from the split spec in api/spec/ (ADR-0029, ADR-0066): first the bundle
# api/openapi.yaml with the Redocly CLI version that REDOCLY_VERSION names (set by tasks/api.yml), then,
# from the bundle, the Go server interface and the client of pkg/mykit (ADR-0093) with the oapi-codegen version
# pinned in tools/go.mod, the per-operation security metadata that the client API enforces
# (internal/interface/clientapi/internal/securitygen), and the TypeScript types of @mycroblog/mykit (pkg/mykit/ts) with
# the openapi-typescript version pinned in its package.json (needs `scripts/task.sh web:install`). Every target is
# committed; the web client reads the types of @mycroblog/mykit (ADR-0093 §3).
#
#   scripts/generate.sh          regenerate every target in place
#   scripts/generate.sh --check  generate the committed targets into a scratch directory and fail if they differ
#
# Generated files get the SPDX header that the generators omit: MIT for pkg/mykit (ADR-0093 §2), AGPL-3.0-only for
# the rest.
set -euo pipefail

: "${REDOCLY_VERSION:?REDOCLY_VERSION is not set; run scripts/task.sh api:generate}"

root="$(cd "$(dirname "$0")/.." && pwd)"
source_spec="api/spec/openapi.yaml"
bundle_out="api/openapi.yaml"
header='// SPDX-License-Identifier: AGPL-3.0-only'

# The header of the bundle, which redocly bundle writes without comments.
# shellcheck disable=SC2016 # the backquotes are Markdown, not a command substitution
bundle_header='# SPDX-License-Identifier: MIT
#
# Code generated by `scripts/task.sh api:generate` from api/spec/ with `redocly bundle`. DO NOT EDIT.
# The client API (ADR-0007, ADR-0016): edit the files in api/spec/ and run `scripts/task.sh api:generate` (ADR-0066).
# docs/architecture/client-api.md explains how to add an endpoint.'

# bundle OUT writes the bundle of the split spec to OUT.
bundle() {
  local out="$1" log
  mkdir -p "$(dirname "$out")"
  if ! log="$(cd "$root" && REDOCLY_TELEMETRY=off REDOCLY_SUPPRESS_UPDATE_NOTICE=true \
    bunx --bun "@redocly/cli@$REDOCLY_VERSION" bundle "$source_spec" --output "$out.tmp.yaml" 2>&1)"; then
    printf '%s\n' "$log" >&2
    echo "redocly bundle of $source_spec failed" >&2
    exit 1
  fi
  printf '%s\n' "$bundle_header" | cat - "$out.tmp.yaml" > "$out"
  rm "$out.tmp.yaml"
}

# Targets as "<oapi-codegen config> <output file> <license>", relative to the repository root.
targets=(
  "internal/interface/clientapi/oapi-codegen.yaml internal/interface/clientapi/api.gen.go AGPL-3.0-only"
  "pkg/mykit/oapi-codegen.yaml pkg/mykit/api.gen.go MIT"
)

# The security metadata, relative to the repository root.
security_out="internal/interface/clientapi/security.gen.go"

# The types of @mycroblog/mykit, relative to the repository root (committed, MIT).
mykit_ts_out="pkg/mykit/ts/src/schema.gen.ts"

# generate CONFIG OUT LICENSE writes the code that CONFIG generates from the spec to OUT, with the SPDX header of
# LICENSE.
generate() {
  local config="$1" out="$2" license="$3"
  mkdir -p "$(dirname "$out")"
  (cd "$root" && go tool -modfile=tools/go.mod oapi-codegen -config "$config" -o "$out.tmp" "$spec")
  printf '// SPDX-License-Identifier: %s\n\n' "$license" | cat - "$out.tmp" > "$out"
  rm "$out.tmp"
}

# generate_ts PACKAGE OUT LICENSE writes the TypeScript types of the spec to OUT with the openapi-typescript of the
# package directory PACKAGE, under the SPDX header of LICENSE.
generate_ts() {
  local package="$1" out="$2" license="$3"
  mkdir -p "$(dirname "$out")"
  (cd "$root" && "$package/node_modules/.bin/openapi-typescript" "$spec" --output "$out.tmp" >/dev/null)
  printf '// SPDX-License-Identifier: %s\n' "$license" | cat - "$out.tmp" > "$out"
  rm "$out.tmp"
}

# generate_security OUT writes the security metadata of the spec to OUT.
generate_security() {
  local out="$1"
  mkdir -p "$(dirname "$out")"
  (cd "$root" && go run ./internal/interface/clientapi/internal/securitygen -o "$out.tmp" "$spec")
  printf '%s\n\n' "$header" | cat - "$out.tmp" > "$out"
  rm "$out.tmp"
}

# The generators read the bundle at $spec.
if [ "${1:-}" != "--check" ]; then
  bundle "$root/$bundle_out"
  spec="$root/$bundle_out"
  for target in "${targets[@]}"; do
    read -r config out license <<< "$target"
    generate "$config" "$root/$out" "$license"
  done
  generate_security "$root/$security_out"
  generate_ts pkg/mykit/ts "$root/$mykit_ts_out" MIT
  exit 0
fi

scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
stale=0
bundle "$scratch/$bundle_out"
spec="$scratch/$bundle_out"
if ! diff -u "$root/$bundle_out" "$spec"; then
  stale=1
fi
for target in "${targets[@]}"; do
  read -r config out license <<< "$target"
  generate "$config" "$scratch/$out" "$license"
  if ! diff -u "$root/$out" "$scratch/$out"; then
    stale=1
  fi
done
generate_security "$scratch/$security_out"
if ! diff -u "$root/$security_out" "$scratch/$security_out"; then
  stale=1
fi
generate_ts pkg/mykit/ts "$scratch/$mykit_ts_out" MIT
if ! diff -u "$root/$mykit_ts_out" "$scratch/$mykit_ts_out"; then
  stale=1
fi
if [ "$stale" -ne 0 ]; then
  echo "generated client API code is stale; run 'scripts/task.sh api:generate' and commit the result" >&2
  exit 1
fi
echo "generated client API code is up to date"
