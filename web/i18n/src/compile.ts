// Compiles the catalog of each web package that has one (web/<package>/locales/, ADR-0009 §1, §9) with Lingui into
// web/<package>/src/messages.gen.ts, which the repository does not commit (ADR-0081): each locale's messages in a module
// of its own (messages.<locale>.gen.ts), which messages.gen.ts imports statically into one record, so that the app's
// build puts each locale's strings in a chunk of its own, under the Service Worker's limit of a precached file. It reads
// every locale through the plug-in of format.ts, gives a key a locale lacks the en message (ADR-0009 §2), and adds the
// pseudo-locales en-XA and ar-XB that tools/i18n makes from en. `scripts/task.sh i18n:compile` runs it on Bun before
// the tasks that type-check, lint, test, or build a package.

import { compileMessageOrThrow, type CompiledMessage } from "@lingui/message-utils/compileMessage";
import { isPseudo, loadCatalogFiles, rel, SOURCE, tsNamespaces, writeFileAtomic } from "@my/i18n-tools/catalog";
import { pseudoCatalogs } from "@my/i18n-tools/generate";
import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { formatjs } from "./format";

/** locale -> id -> ICU message */
type Messages = Record<string, Record<string, string>>;

/** The messages of every locale of the namespace's catalog, read through the plug-in. */
async function readCatalog(ns: string): Promise<Messages> {
  const messages: Messages = {};
  for (const { path, locale, ns: of } of loadCatalogFiles()) {
    if (of !== ns || isPseudo(locale)) continue;
    const catalog = await formatjs.parse(readFileSync(path, "utf8"), { locale, sourceLocale: SOURCE, filename: path });
    for (const [id, { translation }] of Object.entries(catalog)) {
      if (translation !== undefined) (messages[locale] ??= {})[id] = translation;
    }
  }
  return messages;
}

/** The module of a locale's messages, named after it under the package's src/. */
export const localeModule = (locale: string) => `messages.${locale}.gen.ts`;

/** Whether `file` is a module of a locale's messages that this compile writes. */
const isLocaleModule = (file: string) => /^messages\.[A-Za-z0-9-]+\.gen\.ts$/.test(file);

/**
 * The modules of the namespace's catalog, compiled by Lingui, by their file names under the package's src/: one a
 * locale, and messages.gen.ts, which holds the message ids and imports every locale's into one record.
 */
export async function compile(ns: string): Promise<Record<string, string>> {
  const pkg = tsNamespaces.get(ns);
  if (!pkg) throw new Error(`${ns}: no web package has this catalog`);
  const messages = await readCatalog(ns);
  const source = messages[SOURCE] ?? {};
  const pseudo = await pseudoCatalogs({
    [SOURCE]: { [ns]: Object.fromEntries(Object.entries(source).map(([id, m]) => [id, { defaultMessage: m }])) },
  });
  for (const [locale, namespaces] of Object.entries(pseudo)) {
    messages[locale] = Object.fromEntries(
      Object.entries(namespaces[ns] ?? {}).map(([id, e]) => [id, e.defaultMessage]),
    );
  }

  const ids = Object.keys(source).sort();
  const compiled: Record<string, Record<string, CompiledMessage>> = {};
  const errors: string[] = [];
  for (const locale of Object.keys(messages).sort()) {
    const out: Record<string, CompiledMessage> = (compiled[locale] = {});
    for (const id of ids) {
      const message = messages[locale]?.[id] ?? source[id] ?? "";
      try {
        out[id] = compileMessageOrThrow(message);
      } catch (e) {
        errors.push(`${rel(pkg)}/locales/${locale} ${id}: ${(e as Error).message}`);
      }
    }
  }
  if (errors.length) throw new Error(`Lingui cannot compile:\n${errors.join("\n")}`);

  const header = [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "",
    `// Code generated by @my/i18n (scripts/task.sh i18n:compile) from ${rel(pkg)}/locales; DO NOT EDIT.`,
    "",
    'import type { Messages } from "@lingui/core";',
  ];
  const locales = Object.keys(compiled);
  const modules: Record<string, string> = {};
  for (const locale of locales)
    modules[localeModule(locale)] = [
      ...header,
      "",
      `/** The messages of ${locale}, compiled by Lingui; a key the locale lacks holds the en message. */`,
      `export const messages: Messages = ${JSON.stringify(compiled[locale], null, 2)};`,
      "",
    ].join("\n");
  const name = (i: number) => `locale${String(i)}`;
  modules["messages.gen.ts"] = [
    ...header,
    ...locales.map(
      (locale, i) => `import { messages as ${name(i)} } from "./${localeModule(locale).replace(/\.ts$/, "")}";`,
    ),
    "",
    "/** The keys of the catalog: Lingui's message ids. */",
    `export type MessageId = ${ids.map((id) => JSON.stringify(id)).join(" | ") || "never"};`,
    "",
    "/** The messages of each locale, compiled by Lingui; a key the locale lacks holds the en message. */",
    "export const messages: Readonly<Record<string, Messages>> = {",
    ...locales.map((locale, i) => `  ${JSON.stringify(locale)}: ${name(i)},`),
    "};",
    "",
  ].join("\n");
  return modules;
}

if (import.meta.main) {
  for (const [ns, pkg] of tsNamespaces) {
    const modules = await compile(ns);
    const src = join(pkg, "src");
    // A locale the catalog no longer has leaves no module behind.
    for (const file of existsSync(src) ? readdirSync(src) : [])
      if (isLocaleModule(file) && !(file in modules)) {
        rmSync(join(src, file));
        console.log(`removed ${rel(join(src, file))}`);
      }
    for (const [file, text] of Object.entries(modules)) {
      const path = join(src, file);
      if (writeFileAtomic(path, text)) console.log(`wrote ${rel(path)}`);
    }
  }
}
