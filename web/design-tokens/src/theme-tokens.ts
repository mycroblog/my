// The tokens a server theme may override (ADR-0059 §2), with their kinds, defaults and bounds, and the contrast
// pairs an override is checked against, for the Go domain that validates and serves themes:
// internal/domain/instance/theme_tokens.gen.go, which is committed (ADR-0081). `scripts/task.sh web:tokens-gen`
// writes it with `bun src/theme-tokens.ts`; theme-tokens.test.ts fails when the committed file is stale.
import { color, contrastPairs, properties } from "./tokens";

/** The kinds of value the Go domain validates an override against (instance.ThemeTokenKind). */
type Kind = "color" | "length" | "number" | "font-family" | "duration";

/**
 * How a custom property is treated: overridable with a kind and, for a length (rem), a number or a duration (ms),
 * the bounds that keep the screens usable; or fixed, without a kind. Every property matches one rule, so a new
 * token is classified before it reaches the Go list.
 */
type Rule = { pattern: RegExp; kind?: Kind; min?: number; max?: number };

const rules: readonly Rule[] = [
  // Fixed: a pair with an avatar holds its contrast only with this value.
  { pattern: /^--color-avatar-/ },
  { pattern: /^--color-/, kind: "color" },
  { pattern: /^--font-sans$/, kind: "font-family" },
  { pattern: /^--text-[a-z]+$/, kind: "length", min: 0.625, max: 3 },
  { pattern: /^--text-[a-z]+--line-height$/, kind: "number", min: 1, max: 2.5 },
  { pattern: /^--radius-/, kind: "length", min: 0, max: 2 },
  { pattern: /^--duration-/, kind: "duration", min: 0, max: 1000 },
  // Fixed: the weights and letter spacing of the type scale, and the sizes and mixes of the components, whose
  // values hold a touch target, a ring around a control, or a contrast of a mix.
  { pattern: /^--text-[a-z]+--(font-weight|letter-spacing)$/ },
  { pattern: /^--font-weight-/ },
  {
    pattern:
      /^--(control|icon-button|focus-ring|press|spinner|icon|avatar|menu|disclosure|content|entry|embed|media|chip)-/,
  },
  // Fixed: Tailwind maps a shadow to its utilities.
  { pattern: /^--shadow-/ },
];

type Token = { name: string; kind: Kind; light?: string; dark?: string; value?: string; min?: number; max?: number };

/** The overridable tokens, in the order of `properties`, named without the leading `--`. */
export function themeTokens(): Token[] {
  const tokens: Token[] = [];
  for (const [property, value] of Object.entries(properties)) {
    const rule = rules.find((r) => r.pattern.test(property));
    if (rule === undefined) throw new Error(`${property} matches no rule of src/theme-tokens.ts: overridable or fixed`);
    if (rule.kind === undefined) continue;
    const token: Token = { name: property.slice(2), kind: rule.kind };
    if (rule.kind === "color") {
      const c = color[property.slice("--color-".length) as keyof typeof color];
      token.light = c.light;
      token.dark = c.dark;
    } else {
      token.value = value;
    }
    if (rule.min !== undefined) token.min = rule.min;
    if (rule.max !== undefined) token.max = rule.max;
    tokens.push(token);
  }
  for (const { fg, bg } of contrastPairs) {
    for (const name of [fg, bg]) {
      if (!tokens.some((t) => t.name === `color-${name}`))
        throw new Error(`the contrast pair ${fg} on ${bg} names --color-${name}, which is not overridable`);
    }
  }
  return tokens;
}

const goKinds: Record<Kind, string> = {
  color: "ThemeTokenColor",
  length: "ThemeTokenLength",
  number: "ThemeTokenNumber",
  "font-family": "ThemeTokenFontFamily",
  duration: "ThemeTokenDuration",
};

/** A Go interpreted string literal: JSON's escapes are a subset of Go's. */
const goString = (s: string) => JSON.stringify(s);

/** The Go file, as gofmt formats it. */
export function renderGo(): string {
  const lines = [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "",
    "// Code generated by web/design-tokens/src/theme-tokens.ts from @my/design-tokens; DO NOT EDIT.",
    "// Regenerate with `scripts/task.sh web:tokens-gen`.",
    "",
    "package instance",
    "",
    "// themeTokens are the tokens a server theme may override, in the order of @my/design-tokens.",
    "var themeTokens = []ThemeToken{",
  ];
  for (const t of themeTokens()) {
    const fields = [`Name: ${goString(t.name)}`, `Kind: ${goKinds[t.kind]}`];
    if (t.light !== undefined) fields.push(`Light: ${goString(t.light)}`, `Dark: ${goString(t.dark ?? "")}`);
    if (t.value !== undefined) fields.push(`Default: ${goString(t.value)}`);
    if (t.min !== undefined) fields.push(`Min: ${t.min}`);
    if (t.max !== undefined) fields.push(`Max: ${t.max}`);
    lines.push(`\t{${fields.join(", ")}},`);
  }
  lines.push(
    "}",
    "",
    "// themeContrastPairs are the foreground / background pairs of the color tokens and their minimum",
    "// contrast ratios (WCAG 2.2 AA).",
    "var themeContrastPairs = []ContrastPair{",
  );
  for (const p of contrastPairs) {
    lines.push(`\t{FG: ${goString(`color-${p.fg}`)}, BG: ${goString(`color-${p.bg}`)}, Minimum: ${p.minimum}},`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** The path of the Go file, relative to this file. */
export const goFile = new URL("../../../internal/domain/instance/theme_tokens.gen.go", import.meta.url);

if (import.meta.main) await Bun.write(goFile, renderGo());
