/**
 * The message id of `key` in `table`. The topics' table (topics.ts) checks by its types that every key a page names
 * has its words; a key that has none reads as the key itself would.
 */
export const wordOf = (table: Readonly<Record<string, MessageId>>, key: string): MessageId =>
  table[key] ?? (key as MessageId);
