// The one layout of every email the server sends (ADR-0086 §2): the server's logo when it has one, the paragraphs,
// the action, and the signature, in a card on a backdrop. Bun renders it at build time, without Vite, into the Go
// html/template internal/app/kernel/mail_frame.gen.html, which is committed and embedded (ADR-0081):
// `scripts/task.sh mail:frame` writes it with `bun web/mail/src/frame.tsx`, which refuses a layout that `checkFrame`
// refuses, and frame.test.ts fails when the committed file is stale. The template's data is the one of
// `MailComposer.html` in internal/app/kernel/mail_composer.go; no word is the layout's own, every one comes from the
// server's catalogs.
import { renderToStaticMarkup } from "react-dom/server";
import { checkFrame } from "./check";
import { Comment, Go, toTemplate, value } from "./go";
import { Body, Button, Card, cardWidth, dir, Line, Link, LogoImage, Rule, schemeStyles, start } from "./parts";

/** The rows of the card. */
function Rows() {
  return (
    <>
      <Go action="with .Logo">
        <tr>
          <td align={start} style={{ padding: "0 0 24px 0" }}>
            <LogoImage />
            <Go action="with $.LogoDark">
              <LogoImage dark hidden />
            </Go>
          </td>
        </tr>
      </Go>
      <Go action="range .Paragraphs">
        <Line>{value(".")}</Line>
      </Go>
      <Go action="with .Action">
        <Go
          action="if .URL"
          otherwise={
            <>
              <Line>{value(".Label")}</Line>
              <Line muted>{value(".Text")}</Line>
            </>
          }
        >
          <Button href={value(".URL")}>{value(".Label")}</Button>
          <Line muted align="center" space="0 0 24px 0">
            <Link href={value(".URL")} long>
              {value(".URL")}
            </Link>
          </Line>
        </Go>
      </Go>
      <Rule />
      <Line muted space="0 0 4px 0">
        {value(".Site.Name")}
      </Line>
      <Go action="if .SiteURL">
        <Line muted space="0 0 4px 0">
          <Link href={value(".SiteURL")}>{value(".SiteURL")}</Link>
        </Line>
      </Go>
      <Go action="with .Contact">
        <Line muted space="0 0 4px 0">
          {value(".")}
        </Line>
      </Go>
      <Line muted space="12px 0 0 0">
        {value(".Reason")}
      </Line>
      <Go action="with .Unsubscribe">
        <Line muted space="4px 0 0 0">
          {value(".Before")}
          <Go action="with .URL">
            <Link href={value(".")} long>
              {value(".")}
            </Link>
          </Go>
          {value(".After")}
        </Line>
      </Go>
    </>
  );
}

/** The whole email: its language and direction from the locale, the schemes' styles, and the card. */
function Frame() {
  return (
    <html lang={value(".Lang")} dir={dir}>
      <head>
        <meta httpEquiv="Content-Type" content="text/html; charset=UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <meta name="color-scheme" content="light dark" />
        <meta name="supported-color-schemes" content="light dark" />
        <title>{value(".Subject")}</title>
        <style>{schemeStyles()}</style>
      </head>
      <Body>
        {/* Outlook on Windows ignores max-width: a table of the card's width holds it there. */}
        <Comment
          text={`[if mso]><table role="presentation" border="0" cellpadding="0" cellspacing="0" width="${cardWidth + 32}" align="center"><tr><td><![endif]`}
        />
        <Card>
          <Rows />
        </Card>
        <Comment text="[if mso]></td></tr></table><![endif]" />
      </Body>
    </html>
  );
}

const header = [
  "{{/* SPDX-License-Identifier: AGPL-3.0-only */}}",
  "{{/* Code generated by web/mail/src/frame.tsx from @my/mail; DO NOT EDIT. Regenerate with `scripts/task.sh mail:frame`. */}}",
  "{{/* The HTML layout of every email (ADR-0086 §2); its colors are .Colors, the server's theme. */}}",
].join("\n");

/**
 * The template with a line for each row, table and part of the head, and the actions that lead to it, so that a
 * change shows in the diff of the template and of the emails' golden files: a line break between them is no text an
 * email shows, unlike one inside a cell.
 */
const lines = (template: string) =>
  template
    .replace(/((?:\{\{[^{}]*\}\})*)(<(?:\/?(?:html|head|body|table|tbody|tr)|meta|title|style)\b)/g, "\n$1$2")
    .trimStart();

/** The Go template of the layout. */
export function renderFrame(): string {
  // React preloads each image with a <link> in the head; an email loads nothing but the logo it shows.
  const markup = renderToStaticMarkup(<Frame />).replace(/<link rel="preload" as="image" href="[^"]*"\/>/g, "");
  return `${header}\n<!doctype html>\n${lines(toTemplate(markup))}\n`;
}

/** The path of the generated template, relative to this file. */
export const frameFile = new URL("../../../internal/app/kernel/mail_frame.gen.html", import.meta.url);

if (import.meta.main) {
  const frame = renderFrame();
  const problems = checkFrame(frame);
  if (problems.length > 0) {
    console.error(`the email layout breaks the rules of its HTML (ADR-0086 §2):\n${problems.join("\n")}`);
    process.exit(1);
  }
  await Bun.write(frameFile, frame);
}
