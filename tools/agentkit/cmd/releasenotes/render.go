// draft is the generated text, and the facts that the prose must name.
type draft struct {
	sections, mykit, mybot string
	required               []requiredItem
}

// doc links a document as of the release's tag.
func doc(version, path, title string) string {
	return fmt.Sprintf("[%s](https://github.com/mycroblog/my/blob/%s/%s)", title, version, path)
}

// firstRelease has nothing to compare with: nothing can break or upgrade, and the commits marked ! before it changed
// no release that anyone runs.
func firstRelease(o options, cur facts) draft {
	var b strings.Builder
	b.WriteString("<!-- Draft generated by scripts/release-notes.sh for the first release: there is no earlier release to compare with. Review it before publishing. -->\n\n")
	fmt.Fprintf(&b, "## Upgrading\n\nNone. This is the first release, so there is nothing to upgrade from. To start an instance, follow %s and %s.\n\n",
		doc(o.version, "docs/operations/running.md", "Running"), doc(o.version, "docs/operations/database.md", "Database"))
	b.WriteString("## Breaking changes\n\nNone. This is the first release.\n\n")

	fmt.Fprintf(&b, "## API changes\n\nThe first release of the client API (`/api/v1`): %d operations and %d scopes, described by %s.\n\n",
		len(cur.api.operations), len(cur.api.scopes), doc(o.version, openAPIFile, "api/openapi.yaml"))
	var deprecated []string
	for _, op := range sortedOperations(cur.api.operations) {
		if op.deprecated {
			deprecated = append(deprecated, deprecationItem(op))
		}
	}
	if len(deprecated) > 0 {
		list(&b, "Deprecated from the start", deprecated)
	}
	return draft{
		sections: b.String(),
		mykit:    "None. This is the first release of mykit.\n",
		mybot:    "None. This is the first release of mybot.\n",
		required: []requiredItem{},
	}
}

func laterRelease(o options, old, cur facts, commits []commit, schema []string) draft {
	api := compareAPI(old.api, cur.api, o.today, o.previous)
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- Draft generated by scripts/release-notes.sh, compared with %s. Review it before publishing, and fill what the comments in each section ask for.", o.previous)
	if isPatch(o.version) {
		b.WriteString(" A patch release is compared with the previous minor version, the upgrade it supports: remove what an earlier patch of this minor version already announced.")
	}
	b.WriteString(" -->\n\n")
	upgrading(&b, o, old, cur)
	breaking(&b, o, old, cur, api, commits, schema)
	apiChanges(&b, o, api)
	return draft{
		sections: b.String(),
		mykit:    library("mykit", commits, api),
		mybot:    library("mybot", commits, apiComparison{}),
		required: requiredItems(old, cur, api, commits),
	}
}

func isPatch(version string) bool {
	core, _, _ := strings.Cut(version, "-")
	parts := strings.Split(core, ".")
	return len(parts) == 3 && parts[2] != "0"
}

// minorOf is vX.Y of vX.Y.Z[-pre].
func minorOf(version string) string {
	core, _, _ := strings.Cut(version, "-")
	return core[:strings.LastIndexByte(core, '.')]
}

func upgrading(b *strings.Builder, o options, old, cur facts) {
	known := map[string]bool{}
	for _, s := range old.steps {
		known[s.key] = true
	}
	var steps, projections, through, required []string
	for _, s := range cur.steps {
		if known[s.key] {
			continue
		}
		item := fmt.Sprintf("`%s`: %s", s.key, s.description)
		if !s.runs {
			item += " (only recorded: its contract has shipped, so there is nothing left to rewrite)"
		}
		steps = append(steps, item)
		for _, p := range s.projections {
			if !slices.Contains(projections, "`"+p+"`") {
				projections = append(projections, "`"+p+"`")
			}
		}
	}
	oldPrereqs := map[string]bool{}
	for _, p := range old.prereqs {
		oldPrereqs[p.key] = true
	}
	for _, p := range cur.prereqs {
		if !oldPrereqs[p.key] {
			through = append(through, fmt.Sprintf("`%s`: this release removes data that it carried over, so upgrade through `%s` first", p.key, p.via))
		}
	}
	for _, key := range sortedKeys(cur.settings) {
		if _, had := old.settings[key]; !had && cur.settings[key].required == "yes" {
			required = append(required, fmt.Sprintf("`%s`: a new required setting", key))
		}
	}

	fmt.Fprintf(b, "## Upgrading\n\nFollow %s. Run `my db upgrade -check` and `my db upgrade` even when this section lists no step; they then do nothing.\n\n",
		doc(o.version, "docs/operations/database.md#upgrading", "Upgrading"))
	list(b, "Data upgrade steps", steps)
	list(b, "Projections that `my db upgrade` rebuilds", projections)
	if minorOf(o.version) == minorOf(o.previous) {
		fmt.Fprintf(b, "**Upgrade from**: the same minor version (`%s.Z`).\n\n", minorOf(o.version))
	} else {
		fmt.Fprintf(b, "**Upgrade from**: the same minor version (`%s.Z`), or the latest patch release of the previous one (`%s`).\n\n",
			minorOf(o.version), o.previous)
	}
	if len(through) > 0 {
		list(b, "Upgrade through", through)
	}
	list(b, "To do by hand", required)
	fmt.Fprintf(b, "<!-- Fill by hand: roughly how long each data upgrade step takes on a large instance, and anything else to do before or after. Run this release's `my schema apply -dry-run` on a database of %s to check. -->\n\n", o.previous)
}

func breaking(b *strings.Builder, o options, old, cur facts, api apiComparison, commits []commit, schema []string) {
	settings := settingChanges(old, cur)
	client := slices.Concat(api.removedOperations, api.removedFields, api.removedScopes, api.changedFields)
	schemaItems := make([]string, 0, len(schema))
	for _, f := range schema {
		schemaItems = append(schemaItems, "`"+f+"` changed: review it for removed tables and columns, type changes, and new constraints")
	}

	b.WriteString("## Breaking changes\n\n")
	if len(settings)+len(client)+len(schemaItems)+len(commits) == 0 {
		b.WriteString("None.\n\n")
	} else {
		list(b, "Settings", settings)
		list(b, "Client API", client)
		list(b, "Schema contract", schemaItems)
		commitsByArea(b, commits)
	}
	fmt.Fprintf(b, "<!-- Fill by hand: what each change means for an operator or a client, whether a schema change removes data and which release carried it over (`git diff %s %s -- schema/`), and keep only the commits that break something outside the repository. -->\n\n", o.previous, o.version)
}

func settingChanges(old, cur facts) []string {
	var items []string
	known := map[string]bool{}
	for _, r := range old.retired {
		known[r.key] = true
	}
	retired := map[string]bool{}
	for _, r := range cur.retired {
		retired[r.key] = true
		switch {
		case known[r.key]:
		case r.renamedTo != "":
			items = append(items, fmt.Sprintf("`%s` was renamed to `%s`; the server refuses to start with the old key", r.key, r.renamedTo))
		default:
			items = append(items, fmt.Sprintf("`%s` was removed: %s; the server refuses to start with it", r.key, r.removed))
		}
	}
	for _, key := range sortedKeys(old.settings) {
		before := old.settings[key]
		after, kept := cur.settings[key]
		if !kept {
			if !retired[key] {
				items = append(items, fmt.Sprintf("`%s` is gone without an entry in the renamed and removed settings", key))
			}
			continue
		}
		if before.defaultValue != after.defaultValue {
			items = append(items, fmt.Sprintf("`%s`: the default changed from %s to %s", key, before.defaultValue, after.defaultValue))
		}
		if before.required != after.required {
			items = append(items, fmt.Sprintf("`%s`: required changed from %s to %s", key, before.required, after.required))
		}
	}
	return items
}

func commitsByArea(b *strings.Builder, commits []commit) {
	if len(commits) == 0 {
		b.WriteString("**Commits marked `!`**: None.\n\n")
		return
	}
	byArea := map[string][]string{}
	for _, c := range commits {
		for _, area := range c.areas() {
			byArea[area] = append(byArea[area], c.item())
		}
	}
	b.WriteString("**Commits marked `!`**, by area:\n\n")
	for _, area := range sortedKeys(byArea) {
		fmt.Fprintf(b, "- %s\n", area)
		for _, item := range capped(byArea[area]) {
			fmt.Fprintf(b, "  - %s\n", item)
		}
	}
	b.WriteString("\n")
}

// apiComparison is the difference of api/openapi.yaml, as list items.
type apiComparison struct {
	addedOperations, addedFields, addedScopes       []string
	deprecated, removable, keptDeprecated           []string
	removedOperations, removedFields, removedScopes []string
	changedFields                                   []string
	// The bare labels of the operations, for the section of the generated client.
	libraryDeprecated, libraryRemoved []string
}

func compareAPI(old, cur apiSpec, today, previous string) apiComparison {
	var c apiComparison
	compareOperations(&c, old, cur, today, previous)
	addedAndRemoved(cur.schemas, old.schemas, func(name string) {
		c.addedFields = append(c.addedFields, fmt.Sprintf("schema `%s`", name))
	}, func(name string) {
		c.removedFields = append(c.removedFields, fmt.Sprintf("schema `%s`", name))
	})
	for _, field := range sortedKeys(cur.fields) {
		before, had := old.fields[field]
		schema, _, _ := strings.Cut(field, ".")
		switch {
		case !old.schemas[schema]: // A new schema is listed as a whole.
		case !had:
			c.addedFields = append(c.addedFields, "`"+field+"`")
		case before != cur.fields[field]:
			c.changedFields = append(c.changedFields, fmt.Sprintf("`%s`: %s, was %s", field, cur.fields[field], before))
		}
	}
	for _, field := range sortedKeys(old.fields) {
		schema, _, _ := strings.Cut(field, ".")
		if _, kept := cur.fields[field]; !kept && cur.schemas[schema] {
			c.removedFields = append(c.removedFields, "`"+field+"`")
		}
	}
	addedAndRemoved(cur.scopes, old.scopes, func(scope string) {
		c.addedScopes = append(c.addedScopes, "`"+scope+"`")
	}, func(scope string) {
		c.removedScopes = append(c.removedScopes, "scope `"+scope+"`")
	})
	return c
}

func compareOperations(c *apiComparison, old, cur apiSpec, today, previous string) {
	for _, op := range sortedOperations(cur.operations) {
		before, had := old.operations[op.key()]
		if !had {
			c.addedOperations = append(c.addedOperations, op.label())
		} else {
			for _, p := range op.params {
				if !slices.Contains(before.params, p) {
					c.addedFields = append(c.addedFields, fmt.Sprintf("`%s`: parameter `%s`", op.id, p))
				}
			}
			for _, p := range before.params {
				if !slices.Contains(op.params, p) {
					c.removedFields = append(c.removedFields, fmt.Sprintf("`%s`: parameter `%s`", op.id, p))
				}
			}
		}
		switch {
		case !op.deprecated:
		case !had || !before.deprecated:
			c.deprecated = append(c.deprecated, deprecationItem(op))
			c.libraryDeprecated = append(c.libraryDeprecated, op.label())
		case sunsetPassed(op.sunset, today):
			// Only what the previous release, of an earlier minor version, already shipped as deprecated.
			c.removable = append(c.removable, fmt.Sprintf("%s: its Sunset %s has passed", op.label(), op.sunset))
		default:
			c.keptDeprecated = append(c.keptDeprecated, fmt.Sprintf("%s: until its Sunset %s", op.label(), op.sunset))
		}
	}
	for _, op := range sortedOperations(old.operations) {
		if _, kept := cur.operations[op.key()]; kept {
			continue
		}
		item := op.label()
		switch {
		case !op.deprecated:
			item += fmt.Sprintf(": **not deprecated in %s, which only a security fix allows; say why**", previous)
		case !sunsetPassed(op.sunset, today):
			item += fmt.Sprintf(": **its Sunset %s has not passed, which only a security fix allows; say why**", op.sunset)
		}
		c.removedOperations = append(c.removedOperations, item)
		c.libraryRemoved = append(c.libraryRemoved, op.label())
	}
}

// addedAndRemoved calls added for the keys only in cur and removed for those only in old, sorted.
func addedAndRemoved(cur, old map[string]bool, added, removed func(string)) {
	for _, key := range sortedKeys(cur) {
		if !old[key] {
			added(key)
		}
	}
	for _, key := range sortedKeys(old) {
		if !cur[key] {
			removed(key)
		}
	}
}

func deprecationItem(op operation) string {
	item := fmt.Sprintf("%s: Deprecation %s, Sunset %s", op.label(), op.deprecation, op.sunset)
	if description := strings.Join(strings.Fields(op.description), " "); description != "" {
		item += ". " + description
	}
	return item
}

// sunsetPassed compares dates as YYYY-MM-DD; an operation without a date has none that passed.
func sunsetPassed(sunset, today string) bool { return sunset != "" && sunset < today }

func apiChanges(b *strings.Builder, o options, c apiComparison) {
	b.WriteString("## API changes\n\n")
	removed := slices.Concat(c.removedOperations, c.removedFields, c.removedScopes)
	all := slices.Concat(c.addedOperations, c.addedFields, c.addedScopes, c.deprecated, removed, c.changedFields, c.removable, c.keptDeprecated)
	if len(all) == 0 {
		b.WriteString("None.\n\n")
	} else {
		list(b, "Added operations", c.addedOperations)
		list(b, "Added fields", c.addedFields)
		list(b, "Added scopes", c.addedScopes)
		list(b, "Deprecated in this release", c.deprecated)
		list(b, "Removed", removed)
		list(b, "Changed", c.changedFields)
		list(b, "May be removed in this release (deprecated in an earlier release, Sunset passed)", c.removable)
		list(b, "Deprecated earlier and kept", c.keptDeprecated)
	}
	fmt.Fprintf(b, "<!-- Fill by hand: the operation that replaces each deprecated one where its description does not say, and the reason for anything changed without the deprecation period. To read the difference: `git diff %s %s -- api/openapi.yaml`. -->\n\n", o.previous, o.version)
}

// library is the text of a library's section: its commits marked !, and for the generated client the same operations
// as in API changes.
func library(name string, commits []commit, api apiComparison) string {
	var items []string
	for _, c := range commits {
		if c.touches(name) {
			items = append(items, c.item())
		}
	}
	var b strings.Builder
	if len(items)+len(api.libraryDeprecated)+len(api.libraryRemoved) == 0 {
		b.WriteString("None.\n\n")
	} else {
		list(&b, "Commits marked `!`", items)
		if name == "mykit" {
			list(&b, "Deprecated in the generated client", api.libraryDeprecated)
			list(&b, "Removed from the generated client", api.libraryRemoved)
		}
	}
	fmt.Fprintf(&b, "<!-- Fill by hand: what each change means for a user of %s; the script only finds the commits. -->\n", name)
	return b.String()
}

// list writes a bold title and its items, or says None.
func list(b *strings.Builder, title string, items []string) {
	if len(items) == 0 {
		fmt.Fprintf(b, "**%s**: None.\n\n", title)
		return
	}
	fmt.Fprintf(b, "**%s**:\n\n", title)
	for _, item := range capped(items) {
		fmt.Fprintf(b, "- %s\n", item)
	}
	b.WriteString("\n")
}

func capped(items []string) []string {
	if len(items) <= maxItems {
		return items
	}
	return append(slices.Clone(items[:maxItems]), "... and "+strconv.Itoa(len(items)-maxItems)+" more")
}

func sortedKeys[V any](m map[string]V) []string { return slices.Sorted(maps.Keys(m)) }

func sortedOperations(m map[string]operation) []operation {
	ops := make([]operation, 0, len(m))
	for _, key := range sortedKeys(m) {
		ops = append(ops, m[key])
	}
	return ops
}
