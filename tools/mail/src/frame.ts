// Compiles the email layout frame.mjml with MJML into the Go html/template that kernel.MailComposer embeds
// (ADR-0086 §2). The output is committed because Go reads it (ADR-0081):
//
//   bun run src/frame.ts           write internal/app/kernel/mail_frame.gen.html (`scripts/task.sh mail:gen`)
//   bun run src/frame.ts --check   fail when the committed file differs from what this generates (`scripts/task.sh mail:gen-check`)
//
// Colors come from the defaults of the design tokens in the committed Go token list, which web:tokens keeps in step
// with app/ui/src/theme.css (ADR-0059). MJML runs with `fonts: {}`, so the output loads no web font.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import mjml2html from "mjml";

const root = resolve(import.meta.dir, "../../..");
const sourcePath = resolve(import.meta.dir, "../frame.mjml");
const tokensPath = resolve(root, "internal/domain/instance/theme_tokens.gen.go");
const outPath = resolve(root, "internal/app/kernel/mail_frame.gen.html");

/** The light and dark defaults of every color token, by token name (`color-surface`). */
function readColors(): Map<string, { light: string; dark: string }> {
  const colors = new Map<string, { light: string; dark: string }>();
  const line = /\{Name: "(color-[a-z-]+)", Kind: ThemeTokenColor, Light: "(#[0-9a-f]{6})", Dark: "(#[0-9a-f]{6})"/g;
  for (const [, name, light, dark] of readFileSync(tokensPath, "utf8").matchAll(line)) {
    colors.set(name!, { light: light!, dark: dark! });
  }
  return colors;
}

/** Replaces each %color-NAME:SCHEME% of the source with the token's default. */
function substituteColors(source: string): string {
  const colors = readColors();
  return source.replace(/%(color-[a-z-]+):(light|dark)%/g, (marker, name: string, scheme: "light" | "dark") => {
    const color = colors.get(name);
    if (color === undefined) throw new Error(`frame.mjml: ${marker} names no opaque color token`);
    return color[scheme];
  });
}

async function generate(): Promise<string> {
  const source = substituteColors(readFileSync(sourcePath, "utf8"));
  const { html, errors } = await mjml2html(source, {
    fonts: {},
    keepComments: false,
    validationLevel: "strict",
    filePath: sourcePath,
  });
  if (errors.length > 0) throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
  if (/https?:\/\//.test(html.replaceAll("http://www.w3.org/", ""))) {
    throw new Error("the compiled frame refers to an external resource");
  }
  return (
    "{{/* SPDX-License-Identifier: AGPL-3.0-only */}}\n" +
    "{{/* Generated by tools/mail/src/frame.ts from tools/mail/frame.mjml (scripts/task.sh mail:gen); do not edit. */}}\n" +
    templatize(html.trim()) +
    "\n"
  );
}

/**
 * Turns MJML's output into a template that keeps working in html/template:
 *
 * - MJML's attributes of direction and alignment are enums that its validator checks, so they cannot hold a template
 *   action. MJML writes its defaults (`ltr`, `left`); they become the recipient's direction (`{{$.Dir}}`) and the
 *   side text starts on (`{{$.Start}}`, `left` or `right`), which old clients need instead of `start`.
 * - html/template drops HTML comments, and Outlook reads the layout of its conditional comments
 *   (`<!--[if mso]>...<![endif]-->`). Each comment becomes `{{comment `...`}}`, which writes the comment as it is.
 *   The comments are constants of this file, never data.
 */
function templatize(html: string): string {
  const out = html
    .replaceAll("direction:ltr", "direction:{{$.Dir}}")
    .replaceAll("text-align:left", "text-align:{{$.Start}}")
    .replaceAll('align="left"', 'align="{{$.Start}}"')
    .replace(/<!--[\s\S]*?-->/g, (comment) => {
      if (comment.includes("`") || comment.includes("{{"))
        throw new Error(`a comment cannot become a template action: ${comment}`);
      return "{{comment `" + comment + "`}}";
    });
  if (/\b(ltr|text-align:left)\b/.test(out.replaceAll("{{", "")))
    throw new Error("a left-to-right default is left in the frame");
  return out;
}

const out = await generate();
if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(outPath, "utf8");
  } catch {
    // A missing file is stale too.
  }
  if (committed !== out) {
    console.error("internal/app/kernel/mail_frame.gen.html is stale: run `scripts/task.sh mail:gen` and commit it");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, out);
}
