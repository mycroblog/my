// Package db implements the key-value store port on the application database (kv = "db",
// the default), for both SQLite (internal/adapter/db/sqlite) and PostgreSQL
// (internal/adapter/db/postgres). It needs no extra middleware (NFR-COST-2) and its entries
// are shared by every process on the database, so rate limits hold across instances.
//
// Entries live in the kv_entries table (data-model §4.10). Every operation is one short
// transaction of the database's UnitOfWork; IncrBy is a single upsert (preceded on SQLite by
// removing the expired entry, which BEGIN IMMEDIATE makes atomic with it), and CompareAndSwap
// one conditional statement on PostgreSQL and a read and a write in one BEGIN IMMEDIATE
// transaction on SQLite.
//
// The queries are generated by sqlc from queries/<dialect>/kv (see sqlc.yaml).
package db

import (
	"context"
	"errors"
	"fmt"
	"strconv"
	"time"

	"github.com/mycroblog/my/internal/app/kernel"
	"github.com/mycroblog/my/internal/app/uow"
)

// store runs the dialect's queries inside a transaction of the dialect's UnitOfWork.
// expiresAt is nil for an entry that never expires.
type store interface {
	get(ctx context.Context, tx uow.Tx, namespace, key string, now time.Time) ([]byte, bool, error)
	set(ctx context.Context, tx uow.Tx, namespace, key string, value []byte, expiresAt *time.Time) error
	del(ctx context.Context, tx uow.Tx, namespace, key string) error
	incr(ctx context.Context, tx uow.Tx, namespace, key string, initial []byte, expiresAt *time.Time, now time.Time) ([]byte, error)
	// swap is kernel.KeyValueStore.CompareAndSwap in tx.
	swap(ctx context.Context, tx uow.Tx, namespace, key string, old, value []byte, expiresAt *time.Time, now time.Time) (bool, error)
	deleteExpired(ctx context.Context, tx uow.Tx, now time.Time, limit int) (int64, error)
}

// Store is the database key-value store.
type Store struct {
	db    uow.UnitOfWork
	st    store
	clock kernel.Clock
}

var _ kernel.KeyValueStore = (*Store)(nil)

func (s *Store) expiry(ttl time.Duration) *time.Time {
	if ttl <= 0 {
		return nil
	}
	t := s.clock.Now().Add(ttl)
	return &t
}

// Get implements kernel.KeyValueStore.
func (s *Store) Get(ctx context.Context, namespace, key string) ([]byte, error) {
	now := s.clock.Now()
	var (
		value []byte
		found bool
	)
	err := s.db.Tx(ctx, func(tx uow.Tx) error {
		var err error
		value, found, err = s.st.get(ctx, tx, namespace, key, now)
		return err
	})
	if err != nil {
		return nil, fmt.Errorf("kv/db: get %s/%s: %w", namespace, key, err)
	}
	if !found {
		return nil, fmt.Errorf("kv/db: %s/%s: %w", namespace, key, kernel.ErrKeyNotFound)
	}
	if value == nil {
		value = []byte{}
	}
	return value, nil
}

// Set implements kernel.KeyValueStore.
func (s *Store) Set(ctx context.Context, namespace, key string, value []byte, ttl time.Duration) error {
	if value == nil {
		value = []byte{} // the column is NOT NULL
	}
	expiresAt := s.expiry(ttl)
	err := s.db.Tx(ctx, func(tx uow.Tx) error { return s.st.set(ctx, tx, namespace, key, value, expiresAt) })
	if err != nil {
		return fmt.Errorf("kv/db: set %s/%s: %w", namespace, key, err)
	}
	return nil
}

// Delete implements kernel.KeyValueStore.
func (s *Store) Delete(ctx context.Context, namespace, key string) error {
	err := s.db.Tx(ctx, func(tx uow.Tx) error { return s.st.del(ctx, tx, namespace, key) })
	if err != nil {
		return fmt.Errorf("kv/db: delete %s/%s: %w", namespace, key, err)
	}
	return nil
}

// IncrBy implements kernel.KeyValueStore.
func (s *Store) IncrBy(ctx context.Context, namespace, key string, n int64, ttl time.Duration) (int64, error) {
	now := s.clock.Now()
	expiresAt := s.expiry(ttl)
	initial := []byte(strconv.FormatInt(n, 10))
	var value []byte
	err := s.db.Tx(ctx, func(tx uow.Tx) error {
		var err error
		value, err = s.st.incr(ctx, tx, namespace, key, initial, expiresAt, now)
		return err
	})
	if err != nil {
		return 0, fmt.Errorf("kv/db: incr %s/%s: %w", namespace, key, err)
	}
	got, err := strconv.ParseInt(string(value), 10, 64)
	if err != nil {
		return 0, fmt.Errorf("kv/db: incr %s/%s: %w", namespace, key, errors.Join(errors.New("not a counter"), err))
	}
	return got, nil
}

// CompareAndSwap implements kernel.KeyValueStore.
func (s *Store) CompareAndSwap(ctx context.Context, namespace, key string, old, value []byte, ttl time.Duration) (bool, error) {
	now := s.clock.Now()
	expiresAt := s.expiry(ttl)
	var ok bool
	err := s.db.Tx(ctx, func(tx uow.Tx) error {
		var err error
		ok, err = s.st.swap(ctx, tx, namespace, key, old, value, expiresAt, now)
		return err
	})
	if err != nil {
		return false, fmt.Errorf("kv/db: compare and swap %s/%s: %w", namespace, key, err)
	}
	return ok, nil
}

// DeleteExpired implements kernel.KeyValueStore.
func (s *Store) DeleteExpired(ctx context.Context, limit int) (int64, error) {
	if limit <= 0 {
		return 0, nil
	}
	now := s.clock.Now()
	var n int64
	err := s.db.Tx(ctx, func(tx uow.Tx) error {
		var err error
		n, err = s.st.deleteExpired(ctx, tx, now, limit)
		return err
	})
	if err != nil {
		return 0, fmt.Errorf("kv/db: delete expired: %w", err)
	}
	return n, nil
}
