// Package media serves the public media blobs under /media/ (ADR-0005, ADR-0019 §8). Object
// storage with a CDN can serve the same keys directly; this handler serves them when the
// BlobStore cannot (the local file system). The media proxy (ProxyHandler) relays remote media
// files under /media/proxy/ (docs/architecture/federation.md §9).
package media

import (
	"errors"
	"io"
	"log/slog"
	"net/http"
	"path"
	"strconv"

	"github.com/mycroblog/my/internal/app/blob"
	"github.com/mycroblog/my/internal/app/kernel"
)

// PathPrefix is the URL path under which the public blobs are served: the blob of key
// "media/x/r/large.jpg" is at "/media/x/r/large.jpg".
const PathPrefix = "/" + blob.PublicPrefix

// servable lists the media types this handler serves: the outputs of the MediaProcessor. A blob
// of any other type is not served, so that nothing a browser could run (HTML, SVG) is ever
// sent from the instance's origin.
var servable = map[string]bool{"image/jpeg": true, "image/png": true, "image/gif": true, "image/webp": true}

// ProblemWriter writes the error response of an HTTP status, the same one the rest of the
// server uses for that status.
type ProblemWriter func(w http.ResponseWriter, r *http.Request, status int)

// Options configure a Handler.
type Options struct {
	Blobs blob.Store
	// Problem writes error responses; nil writes a plain-text body.
	Problem ProblemWriter
	// Logger logs unexpected errors; nil means slog.Default().
	Logger *slog.Logger
	// Errors receives the errors behind a 500 answer (ADR-0103 §2); nil reports nothing.
	Errors kernel.ErrorReporter
}

// Handler serves GET and HEAD requests for public blobs, with range requests and conditional
// requests when the store's content can seek.
type Handler struct {
	o Options
}

// New returns a Handler on o.
func New(o Options) *Handler {
	if o.Logger == nil {
		o.Logger = slog.Default()
	}
	if o.Errors == nil {
		o.Errors = kernel.NopErrorReporter{}
	}
	if o.Problem == nil {
		o.Problem = func(w http.ResponseWriter, _ *http.Request, status int) {
			w.Header().Set("Cache-Control", "no-store")
			http.Error(w, http.StatusText(status), status)
		}
	}
	return &Handler{o: o}
}

// Router registers handlers for http.ServeMux patterns.
type Router interface {
	Handle(pattern string, h http.Handler)
}

// Register registers the handler on r. A GET pattern also matches HEAD.
func (h *Handler) Register(r Router) {
	r.Handle("GET "+PathPrefix+"{path...}", h)
}

// ServeHTTP implements http.Handler.
func (h *Handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	key := blob.PublicPrefix + r.PathValue("path")
	if blob.ValidateKey(key) != nil {
		h.o.Problem(w, r, http.StatusNotFound)
		return
	}
	rc, info, err := h.o.Blobs.Get(r.Context(), key)
	switch {
	case errors.Is(err, blob.ErrNotFound):
		h.o.Problem(w, r, http.StatusNotFound)
		return
	case err != nil:
		h.o.Logger.ErrorContext(r.Context(), "read media blob", slog.String("key", key), slog.Any("error", err))
		h.o.Errors.Report(r.Context(), kernel.NewErrorEvent(err, "")) // the reporter names the route
		h.o.Problem(w, r, http.StatusInternalServerError)
		return
	}
	defer func() { _ = rc.Close() }()
	if !servable[info.ContentType] {
		h.o.Logger.WarnContext(r.Context(), "media blob of a type that is not served", slog.String("key", key), slog.String("content_type", info.ContentType))
		h.o.Problem(w, r, http.StatusNotFound)
		return
	}

	hd := w.Header()
	// The type detected at upload, never sniffed by the browser (ADR-0019 §8).
	hd.Set("Content-Type", info.ContentType)
	hd.Set("X-Content-Type-Options", "nosniff")
	hd.Set("Content-Security-Policy", "default-src 'none'; sandbox")
	// Public media is embedded by other origins: remote servers' clients and the web client
	// on its own origin (ADR-0019 §9).
	hd.Set("Cross-Origin-Resource-Policy", "cross-origin")
	// Keys are generated by the server and contain only [A-Za-z0-9._-/], so the file name
	// needs no quoting beyond the quotes.
	hd.Set("Content-Disposition", `inline; filename="`+path.Base(key)+`"`)
	// A key is written once, by the processing job of its media file, and names its processing
	// result (ADR-0054 §4).
	hd.Set("Cache-Control", "public, max-age=31536000, immutable")

	if rs, ok := rc.(io.ReadSeeker); ok {
		// An empty name keeps ServeContent from guessing the type from an extension.
		http.ServeContent(w, r, "", info.ModTime, rs)
		return
	}
	hd.Set("Content-Length", strconv.FormatInt(info.Size, 10))
	if r.Method == http.MethodHead {
		return
	}
	if _, err := io.Copy(w, rc); err != nil {
		h.o.Logger.WarnContext(r.Context(), "write media blob", slog.String("key", key), slog.Any("error", err))
	}
}
