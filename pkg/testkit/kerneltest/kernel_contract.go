// ClockContract verifies that c satisfies the kernel.Clock contract: Now returns UTC times
// with millisecond precision and no monotonic clock reading.
func ClockContract(t *testing.T, c kernel.Clock) {
	t.Helper()
	for range 100 {
		now := c.Now()
		if now.Location() != time.UTC {
			t.Fatalf("Now() = %v, want location UTC", now)
		}
		if now.Nanosecond()%int(time.Millisecond) != 0 {
			t.Fatalf("Now() = %v, want millisecond precision", now)
		}
		if now != now.Round(0) {
			t.Fatalf("Now() = %v carries a monotonic clock reading", now)
		}
	}
}

// IDGeneratorContract verifies that g satisfies the kernel.IDGenerator contract.
// clock is the clock g reads its current time from.
//
// NewID must return canonical UUIDv7 strings that strictly increase from call to call,
// including calls within the same millisecond. NewIDAt must return canonical UUIDv7 strings
// whose timestamp is the given time's millisecond (the current time's for a future time,
// the epoch's for a time before it) and which are unique within a millisecond.
// It returns the IDs generated by NewID for further checks.
func IDGeneratorContract(t *testing.T, g kernel.IDGenerator, clock kernel.Clock) []string {
	t.Helper()
	const n = 10_000
	ids := make([]string, n)
	for i := range ids {
		ids[i] = g.NewID()
	}
	prev := ""
	for _, id := range ids {
		checkUUIDv7(t, "NewID()", id)
		if id <= prev {
			t.Fatalf("NewID() = %q after %q, want strictly increasing IDs", id, prev)
		}
		prev = id
	}
	idGeneratorAtContract(t, g, clock)
	return ids
}

func idGeneratorAtContract(t *testing.T, g kernel.IDGenerator, clock kernel.Clock) {
	t.Helper()
	now := clock.Now()
	jst := time.FixedZone("JST", 9*60*60)
	past := []time.Time{
		now.Add(-time.Millisecond),
		now.Add(-time.Hour + 999*time.Microsecond),
		now.Add(-365 * 24 * time.Hour).In(jst),
		time.UnixMilli(0x0123_4567_89ab),
		time.UnixMilli(0),
	}
	for _, at := range past {
		id := g.NewIDAt(at)
		call := fmt.Sprintf("NewIDAt(%v)", at)
		checkUUIDv7(t, call, id)
		if ms, _ := UUIDv7Millis(id); ms != at.UnixMilli() {
			t.Fatalf("%s = %q has timestamp %d, want %d", call, id, ms, at.UnixMilli())
		}
		if floor := kernel.UUIDv7Floor(at); id <= floor {
			t.Fatalf("%s = %q does not sort above its millisecond's floor %q", call, id, floor)
		}
	}

	beforeEpoch := time.UnixMilli(-1)
	if id := g.NewIDAt(beforeEpoch); id <= kernel.UUIDv7Floor(beforeEpoch) {
		t.Fatalf("NewIDAt(%v) = %q, want an ID in the epoch's millisecond", beforeEpoch, id)
	} else if ms, _ := UUIDv7Millis(id); ms != 0 {
		t.Fatalf("NewIDAt(%v) = %q has timestamp %d, want 0", beforeEpoch, id, ms)
	}

	for _, ahead := range []time.Duration{time.Millisecond, 24 * time.Hour, 100 * 365 * 24 * time.Hour} {
		before := clock.Now()
		id := g.NewIDAt(before.Add(ahead))
		after := clock.Now()
		call := fmt.Sprintf("NewIDAt(now + %v)", ahead)
		checkUUIDv7(t, call, id)
		if ms, _ := UUIDv7Millis(id); ms < before.UnixMilli() || ms > after.UnixMilli() {
			t.Fatalf("%s = %q has timestamp %d, want the current time, between %d and %d",
				call, id, ms, before.UnixMilli(), after.UnixMilli())
		}
	}

	// IDs for one millisecond cannot rely on a counter, so the random bits keep them apart.
	at := now.Add(-time.Minute)
	const n = 10_000
	seen := make(map[string]bool, n)
	for range n {
		id := g.NewIDAt(at)
		checkUUIDv7(t, "NewIDAt", id)
		if seen[id] {
			t.Fatalf("NewIDAt(%v) returned %q twice", at, id)
		}
		seen[id] = true
	}
}

// checkUUIDv7 fails t unless id, returned by call, is a canonical UUIDv7 string.
func checkUUIDv7(t *testing.T, call, id string) {
	t.Helper()
	u, err := uuid.Parse(id)
	if err != nil {
		t.Fatalf("%s = %q is not a UUID: %v", call, id, err)
	}
	if u.String() != id {
		t.Fatalf("%s = %q is not canonical, want %q", call, id, u.String())
	}
	if version := u[6] >> 4; version != 7 {
		t.Fatalf("%s = %q has version %d, want 7", call, id, version)
	}
	if variant := u[8] >> 6; variant != 0b10 {
		t.Fatalf("%s = %q has variant %b, want 10", call, id, variant)
	}
}

// UUIDv7Millis returns the unix_ts_ms field of a canonical UUIDv7 string.
// It returns false if id is not a UUID.
func UUIDv7Millis(id string) (int64, bool) {
	u, err := uuid.Parse(id)
	if err != nil {
		return 0, false
	}
	var ms int64
	for _, b := range u[:6] {
		ms = ms<<8 | int64(b)
	}
	return ms, true
}
